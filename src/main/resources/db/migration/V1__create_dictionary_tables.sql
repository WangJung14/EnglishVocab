-- ===========================================
-- V1: Create Dictionary Module tables
-- English Vocabulary Learning Platform
-- ===========================================

-- 1. Dictionary Words
CREATE TABLE dictionary_words (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  word TEXT NOT NULL,
                                  language_code VARCHAR(10) NOT NULL DEFAULT 'en',

                                  source_word_id BIGINT,

                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT uq_dictionary_words_source
                                      UNIQUE (source_word_id),

                                  CONSTRAINT chk_dictionary_word_not_blank
                                      CHECK (length(btrim(word)) > 0)
);

-- 2. Dictionary Senses
CREATE TABLE dictionary_senses (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   word_id BIGINT NOT NULL,

                                   meaning_vi TEXT NOT NULL,
                                   part_of_speech_raw VARCHAR(100),
                                   example TEXT,

                                   source_definition_id BIGINT,
                                   source_link_id BIGINT,

                                   CONSTRAINT fk_dictionary_senses_word
                                       FOREIGN KEY (word_id)
                                           REFERENCES dictionary_words(id)
                                           ON DELETE RESTRICT,

                                   CONSTRAINT uq_dictionary_senses_source_link
                                       UNIQUE (source_link_id),

                                   CONSTRAINT chk_dictionary_meaning_not_blank
                                       CHECK (length(btrim(meaning_vi)) > 0)
);

-- 3. Dictionary Pronunciations
CREATE TABLE dictionary_pronunciations (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                           word_id BIGINT NOT NULL,

                                           ipa TEXT NOT NULL,
                                           region_raw TEXT,

                                           source_pronunciation_id BIGINT,

                                           CONSTRAINT fk_dictionary_pronunciations_word
                                               FOREIGN KEY (word_id)
                                                   REFERENCES dictionary_words(id)
                                                   ON DELETE RESTRICT,

                                           CONSTRAINT uq_dictionary_pronunciations_source
                                               UNIQUE (source_pronunciation_id),

                                           CONSTRAINT chk_dictionary_ipa_not_blank
                                               CHECK (length(btrim(ipa)) > 0)
);

-- 4. Indexes
CREATE INDEX idx_dictionary_words_word
    ON dictionary_words(word);

CREATE INDEX idx_dictionary_senses_word_id
    ON dictionary_senses(word_id);

CREATE INDEX idx_dictionary_pronunciations_word_id
    ON dictionary_pronunciations(word_id);
